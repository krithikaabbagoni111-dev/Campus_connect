@app.route("/")
def home():
    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute("SELECT COUNT(*) FROM events")
            event_count = cur.fetchone()[0]
            cur.execute("SELECT COUNT(*) FROM students")
            student_count = cur.fetchone()[0]
            cur.execute("SELECT COUNT(*) FROM registrations WHERE status = 'REGISTERED'")
            registration_count = cur.fetchone()[0]
           
            
            cur.execute("""
             SELECT e.event_id, e.title, e.description, e.category,
             TO_CHAR(e.event_date, 'DD Mon YYYY'), e.start_time,
             e.venue, e.capacity, COUNT(r.registration_id)
             FROM events e
             LEFT JOIN registrations r
             ON r.event_id = e.event_id
             AND r.status = 'REGISTERED'
             WHERE e.event_date >= TRUNC(SYSDATE)
             GROUP BY e.event_id, e.title, e.description, e.category,
             e.event_date, e.start_time, e.venue, e.capacity
             ORDER BY e.event_date
             """)
            events = cur.fetchall()

            cur.execute("""
                SELECT category, COUNT(*) FROM events
                WHERE event_date >= TRUNC(SYSDATE)
                GROUP BY category ORDER BY COUNT(*) DESC
            """)
            category_counts = cur.fetchall()
    return render_template(
        "index.html", event_count=event_count, student_count=student_count,
        registration_count=registration_count, events=events,
        category_counts=category_counts
    )


@app.route("/events/add", methods=["POST"])
def add_event():
    form = request.form
    title = form.get("title", "").strip()
    description = form.get("description", "").strip()
    category = form.get("category", "").strip()
    event_date = form.get("event_date", "").strip()
    start_time = form.get("start_time", "").strip()
    venue = form.get("venue", "").strip()
    try:
        capacity = int(form.get("capacity", "0"))
        if not all([title, category, event_date, venue]) or capacity < 1:
            raise ValueError
        with get_connection() as conn:
            with conn.cursor() as cur:
                cur.execute("""
                    INSERT INTO events (title, description, category, event_date,
                                        start_time, venue, capacity, status)
                    VALUES (:title, :description, :category,
                            TO_DATE(:event_date, 'YYYY-MM-DD'), :start_time,
                            :venue, :capacity, 'UPCOMING')
                """, {"title": title, "description": description, "category": category,
                      "event_date": event_date, "start_time": start_time,
                      "venue": venue, "capacity": capacity})
            conn.commit()
        flash("Event published to the VNR VJIET calendar.", "success")
    except ValueError:
        flash("Please complete the required fields and enter a capacity greater than zero.", "error")
    except Exception:
        app.logger.exception("Add event failed")
        flash("Could not add the event. Check the date and Oracle connection.", "error")
    return redirect(url_for("home"))


