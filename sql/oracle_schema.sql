-- Run while connected to the XEPDB1 service as your application schema user.
-- The app.py file can also create these tables automatically.
CREATE TABLE students (
    student_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR2(120) NOT NULL,
    email VARCHAR2(160) NOT NULL UNIQUE,
    department VARCHAR2(80) DEFAULT 'IT',
    academic_year NUMBER DEFAULT 2
);

CREATE TABLE events (
    event_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR2(160) NOT NULL,
    description VARCHAR2(1000),
    category VARCHAR2(50) NOT NULL,
    event_date DATE NOT NULL,
    start_time VARCHAR2(10),
    venue VARCHAR2(160) NOT NULL,
    capacity NUMBER(6) NOT NULL CHECK (capacity > 0),
    status VARCHAR2(20) DEFAULT 'UPCOMING' NOT NULL,
    created_at DATE DEFAULT SYSDATE
);

CREATE TABLE registrations (
    registration_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id NUMBER NOT NULL REFERENCES students(student_id),
    event_id NUMBER NOT NULL REFERENCES events(event_id),
    registered_at DATE DEFAULT SYSDATE,
    status VARCHAR2(20) DEFAULT 'REGISTERED' NOT NULL,
    CONSTRAINT uq_vnr_student_event UNIQUE (student_id, event_id)
);
